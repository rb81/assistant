    def _executor_read(self, request):
        reader_url = os.environ.get("ASSISTANT_MANAGEMENT_READER_URL")
        # A deployed read service never falls back to launching a container on failure.
        if reader_url:
            if request["request"] in READ_SERVICE_REQUESTS and not (
                    request["request"] == "clients.read" and request.get("action") == "reconcile"):
                if reader_url != "http://management-reader:8766":
                    raise PublicSetupError("Management read service address is invalid.")
                try:
                    response = self.reader_client.post(
                        reader_url + "/v1/read", json=request,
                        headers={"Authorization": "Bearer " + read_token(token_path(self.root))},
                    )
                    if response.status_code == 503:
                        raise ManagementExecutorUnavailable("Management reads are temporarily unavailable; retry.")
                    if response.status_code != 200:
                        raise PublicSetupError("Conversation service could not complete this read. "
                                               "Check its health and migrations, then refresh.")
                    body = response.json()
                    if not isinstance(body, dict) or not isinstance(body.get("result"), dict):
                        raise ValueError
                    return body["result"]
                except httpx.HTTPError:
                    raise ManagementExecutorUnavailable("Conversation service is unavailable; retry.") from None
                except ValueError:
                    raise PublicSetupError("Conversation service returned an invalid response.") from None
        executor_url = os.environ.get("ASSISTANT_MANAGEMENT_EXECUTOR_URL")
        if not executor_url:
            return None
        if executor_url != "http://management-docker:2376":
            raise PublicSetupError("Management executor address is invalid.")
        try:
            token = read_token(token_path(self.root))
            with httpx.Client(timeout=180, trust_env=False, follow_redirects=False) as client:
                response = client.post(
                    executor_url + "/v1/read",
                    headers={"Authorization": "Bearer " + token},
                    json=request,
                )
            if response.status_code == 503:
                raise ManagementExecutorUnavailable("Management executor is busy or unavailable; retry.")
            if response.status_code == 409:
                failure_body = response.json()
                if isinstance(failure_body, dict) and failure_body.get("public") is True \
                        and isinstance(failure_body.get("error"), str):
                    raise PublicSetupError(failure_body["error"])
            if response.status_code != 200:
                raise PublicSetupError("The isolated management executor could not complete the read. "
                                       "Check the management-docker service logs.")
            body = response.json()
            if not isinstance(body, dict) or not isinstance(body.get("result"), dict):
                raise PublicSetupError("The isolated management executor returned an invalid response.")
            return body["result"]
        except httpx.HTTPError:
            raise PublicSetupError("The isolated management executor is unavailable; retry the read.") from None
        except ValueError:
            raise PublicSetupError("The isolated management executor returned an invalid response.") from None

