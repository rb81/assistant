def configured_calendars(backend):
    """Match the router's complete OAuth accounts without exposing credential values."""
    accounts = {}
    for provider, title in CALENDAR_PROVIDERS.items():
        for number in range(1, 10):
            suffix = "" if number == 1 else f"_{number}"
            prefix = f"AGENT_CALENDAR_{provider}{suffix}_"
            if all(backend.credentials.get(prefix + key, "").strip()
                   for key in ("CLIENT_ID", "CLIENT_SECRET", "REFRESH_TOKEN")):
                accounts[provider.lower() + suffix] = title if number == 1 else f"{title} calendar {number}"
    return accounts


def setting_presentation(group, spec):
    """Label, section, and help a client should show for one setting."""
    item = settings_schema.catalog_by_env().get(spec.key) or {}
    label, section = (item.get("metadata") or {}).get("label", spec.label), None
    model_section = (item.get("metadata") or {}).get("model_section")
    if model_section:
        section = model_section.replace("_", " ").title()
    if group == "providers":
        section = next((title for title, keys in AI_PROVIDER_FIELDS.items() if spec.key in keys), "General")
    elif group == "provider-privacy":
        section = ("Direct-provider verification" if "VERIFIED" in spec.key else "ZDR routing")
    if spec.key == "AGENT_APPROVALS_CHANNEL":
        label = "Approval delivery"
    elif spec.key == "AGENT_NAMING_MODEL":
        label, section = "Naming model", "Conversation naming"
    elif group == "catalog:search" and spec.key in {
        "AGENT_SEARCH_OPENROUTER_ENABLED", "AGENT_SEARCH_EXA_ENABLED",
        "AGENT_SEARCH_PRIMARY_PROVIDER", "AGENT_SEARCH_EXA_API_KEY",
    }:
        section = "Search providers"
    elif group == "advanced:Model preset tool":
        section = ("Text to speech" if spec.key.startswith("AGENT_TTS_") else
                   "Shared spending limit" if spec.key.startswith("AGENT_MODEL_SERVICE_BUDGET_") else "Model preset tool")
    elif group == "identity":
        if spec.key.startswith("AGENT_ORG_"):
            section = "Organization"
        elif spec.key == "AGENT_ADMIN_NAME":
            section = "About you"
        else:
            section = "Your assistant"
    elif group == "email":
        if spec.key.startswith("AGENT_EMAIL_IMAP_"):
            section = "Incoming mail"
        elif spec.key.startswith("AGENT_EMAIL_SMTP_"):
            section = "Outgoing mail"
        elif spec.key in {"AGENT_EMAIL_ACTIONABLE_SENDERS", "AGENT_EMAIL_ALLOWED_RECIPIENT_DOMAINS"}:
            section = "Access rules"
    elif group == "security":
        if spec.key.startswith("AGENT_SECURITY_DEVELOPMENT_"):
            section = "Development sessions"
        elif spec.key.startswith("AGENT_SECURITY_DECISION_MODEL_"):
            section = "Content screening"
        elif spec.key in {"AGENT_SECURITY_EMAIL_AUTHENTICATION_ENABLED", "AGENT_SECURITY_CONFIRM_NEW_ADMIN_CONVERSATIONS"}:
            section = "Administrator requests"
    provider = re.match(r"^AGENT_CALENDAR_(GOOGLE|OUTLOOK|ZOHO)_", spec.key)
    if provider and group == "calendar":
        section = CALENDAR_PROVIDERS[provider.group(1)]
        prefix = provider.group(1).title() + " "
        if label.startswith(prefix):
            label = label[len(prefix):]
            label = label[:1].upper() + label[1:]
    elif group == "calendar":
        section = "General"
    label = re.sub(r" \((?:[a-z0-9]+(?:, | or ))+[a-z0-9]+\)$", "", label)
    normalized = re.sub(r"^(AGENT_CALENDAR_(?:GOOGLE|OUTLOOK|ZOHO))_[2-9]_", r"\1_", spec.key)
    explanation = FIELD_HELP.get(normalized) or (item.get("metadata") or {}).get("description")
    if provider and explanation:
        # The provider is already clear from the section or account heading.
        explanation = re.sub(r"^(?:Google|Outlook|Zoho): ", "", explanation)
    return label, section, explanation


def configuration_group_details():
    """Ordered group metadata so clients can build navigation without hard-coding names."""
    details = []
    for name, (title, specs) in configuration_groups().items():
        parent, help_text, section = None, GROUP_HELP.get(name), None
        if name.startswith("catalog:"):
            title, parent, help_text = CATALOG_GROUPS.get(
                name.removeprefix("catalog:"), (title.replace("_", " ").capitalize(), None, None))
        elif name.startswith("calendar:"):
            parent = "calendar"
            section = CALENDAR_PROVIDERS[name.removeprefix("calendar:").split("_")[0].upper()]
            help_text = "An additional " + title.rsplit(" ", 2)[0] + " calendar account. Leave blank if unused."
        else:
            parent = ADVANCED_GROUP_PARENTS.get(name)
        if name == "advanced:Model preset tool":
            title = "Model tools & speech"
            help_text = "Model presets and spoken audio use your OpenRouter key and one shared spending limit."
        elif name == "advanced:Memory and workspace indexing":
            title = "Memory & workspace"
            help_text = "Choose whether Assistant maintains memories and indexes workspace files for search."
        owner = parent or name
        group_name = name.removeprefix("catalog:")
        destination = (
            "providers" if name in {"providers", "provider-privacy"} else
            "connections" if owner in {"email", "telegram", "calendar", "zoom", "dropbox"} else
            "models" if owner in {"models", "embeddings", "transcription", "advanced:Model preset tool",
                                 "advanced:Research and notifications"} or group_name in {
                                     "llm", "model_routes", "routing", "fusion", "deep_research",
                                     "speech", "tools",
                                 } else
            "knowledge" if owner in {"advanced:Memory and workspace indexing", "advanced:Web search"}
            or group_name in {"memory", "context", "workspace", "filesystem", "tool_result_cache",
                              "conversion", "web_fetch", "search", "prompt", "skills"} else
            "safety" if owner in {"approvals", "security", "catalog:artifacts", "catalog:sandbox"}
            or group_name in {"security", "artifacts", "sandbox"} else
            "operations" if owner == "deployment" or group_name in {
                "database", "task_agent", "supervisor", "client", "heartbeat", "reminders",
            } else
            "assistant" if group_name in {"identity", "app"} else "assistant"
        )
        details.append({
            "id": name, "title": title, "help": help_text, "parent": parent, "section": section,
            "basic": any(basic_setting(spec.key) for spec in specs) or name in ESSENTIAL_GROUPS,
            "destination": destination,
            **({"advanced_title": ADVANCED_TITLES[name]} if name in ADVANCED_TITLES else {}),
        })
    return details


