import hashlib
import os
import stat
from pathlib import Path
from typing import Optional

from .config import AppConfig
from .database import Database
from .secret_store import SECRET_NAMES


class WorkstreamFileTracker:
    """Track regular workspace files for a persisted workstream job."""

    def __init__(self, db, config: AppConfig, job_id: Optional[int]):
        self.db = db if isinstance(db, Database) else None
        self.config = config
        self.job_id = job_id if isinstance(job_id, int) and job_id > 0 else None
        self.shared_root = Path(config.get("agent.filesystem.shared_root", "/data/share")).resolve()
        self.raw_root = Path(config.get("agent.artifacts.raw_root", "/data/private/artifacts")).resolve()

    @property
    def enabled(self) -> bool:
        return self.db is not None

    def _safe_path(self, path: Path) -> Path:
        candidate = Path(os.path.abspath(os.fspath(path)))
        root = next(
            (allowed for allowed in (self.shared_root, self.raw_root)
             if candidate != allowed and allowed in candidate.parents),
            None,
        )
        if root is None:
            raise ValueError("tracked files must stay under the shared workspace or raw artifacts root")
        relative = candidate.relative_to(root)
        if root == self.shared_root and len(relative.parts) >= 2 and relative.parts[:2] == (".assistant", "docs"):
            raise ValueError("assistant reference documentation cannot be tracked")

        current = root
        for index, part in enumerate(relative.parts):
            current = current / part
            try:
                mode = current.lstat().st_mode
            except FileNotFoundError:
                continue
            if stat.S_ISLNK(mode):
                raise ValueError("symlink paths cannot be tracked")
            if index < len(relative.parts) - 1 and not stat.S_ISDIR(mode):
                raise ValueError("tracked file has a non-directory parent")

        name = candidate.name
        if (name.upper() in SECRET_NAMES or name.startswith(".env") or
                name.upper() in {"AGENT.MD", "AGENT.YAML", "DOCKER-COMPOSE.YML"} or
                candidate.suffix.lower() in {".pem", ".key", ".p12", ".pfx"}):
            raise ValueError("credential and assistant configuration files cannot be tracked")
        return candidate

    def _register(self, path: Path, sha256: Optional[str]) -> Path:
        canonical = self._safe_path(path)
        if self.enabled:
            self.db.execute(
                """
                INSERT INTO workstream_files(path, sha256, source_job_id)
                VALUES (%s, %s, %s)
                ON CONFLICT (path) DO UPDATE
                SET sha256 = COALESCE(EXCLUDED.sha256, workstream_files.sha256),
                    source_job_id = EXCLUDED.source_job_id
                """,
                (str(canonical), sha256, self.job_id),
            )
        return canonical

    def register_path(self, path: Path) -> Path:
        """Register a planned file path before bytes are written."""
        return self._register(path, None)

    def register_derivative_path(
        self,
        path: Path,
        source_path: Path,
        sha256: Optional[str] = None,
    ) -> Path:
        """Register generated bytes under their source file's surviving owners."""
        canonical = self._safe_path(path)
        source = self._safe_path(source_path)
        if not self.enabled:
            return canonical

        base_db = self.db
        if getattr(base_db, "job_id", None) is not None or getattr(base_db, "workstream_id", None) is not None:
            base_db = Database(base_db.database_url)
        source_row = base_db.fetch_one(
            """
            SELECT
              file.source_job_id,
              (SELECT job.workstream_id
               FROM jobs AS job
               JOIN workstreams AS owner ON owner.id = job.workstream_id AND owner.status = 'active'
               WHERE job.id = file.source_job_id) AS active_job_workstream_id
            FROM workstream_files AS file
            WHERE file.path = %s
            """,
            (str(source),),
        )
        active_owners = base_db.fetch_all(
            """
            SELECT DISTINCT attachment.workstream_id
            FROM workstream_files AS file
            JOIN workstream_attachments AS attachment ON attachment.object_id = file.object_id
            JOIN workstreams AS owner ON owner.id = attachment.workstream_id AND owner.status = 'active'
            WHERE file.path = %s
            ORDER BY attachment.workstream_id
            """,
            (str(source),),
        ) if source_row else []

        source_job_id = None
        if source_row and source_row.get("active_job_workstream_id") is not None:
            source_job_id = source_row.get("source_job_id")
            owner_db = base_db.for_job(source_job_id)
        elif active_owners:
            owner_db = base_db.for_workstream(active_owners[0]["workstream_id"])
        else:
            # Unknown or ownerless sources remain explicitly legacy-owned.
            owner_db = base_db

        owner_db.execute(
            """
            INSERT INTO workstream_files(path, sha256, source_job_id)
            VALUES (%s, %s, %s)
            ON CONFLICT (path) DO UPDATE
            SET sha256 = COALESCE(EXCLUDED.sha256, workstream_files.sha256),
                source_job_id = COALESCE(workstream_files.source_job_id, EXCLUDED.source_job_id)
            """,
            (str(canonical), sha256, source_job_id),
        )
        if source_row:
            owner_db.execute(
                """
                INSERT INTO workstream_attachments(workstream_id, object_id)
                SELECT source_attachment.workstream_id, derivative.object_id
                FROM workstream_files AS source_file
                JOIN workstream_attachments AS source_attachment
                  ON source_attachment.object_id = source_file.object_id
                JOIN workstreams AS owner
                  ON owner.id = source_attachment.workstream_id AND owner.status = 'active'
                JOIN workstream_files AS derivative ON derivative.path = %s
                WHERE source_file.path = %s
                ON CONFLICT (workstream_id, object_id) DO NOTHING
                """,
                (str(canonical), str(source)),
            )
        return canonical

    def track_derivative_file(self, path: Path, source_path: Path) -> Path:
        """Update a generated regular file's digest and inherit its source owners."""
        canonical = self._safe_path(path)
        if not stat.S_ISREG(canonical.lstat().st_mode):
            raise ValueError("only regular files can be tracked")
        digest = self._digest(canonical)
        return self.register_derivative_path(canonical, source_path, digest)

    def track_file(self, path: Path) -> Path:
        """Register a completed regular file with its final digest."""
        canonical = self._safe_path(path)
        try:
            mode = canonical.lstat().st_mode
        except OSError:
            raise
        if not stat.S_ISREG(mode):
            raise ValueError("only regular files can be tracked")
        digest = hashlib.sha256()
        with canonical.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
        return self._register(canonical, digest.hexdigest())

    def track_tree(self, path: Path) -> list[Path]:
        target = self._safe_path(path)
        files = []
        if target.is_file():
            return [self.track_file(target)]
        if not target.is_dir():
            return files
        for root, dirs, names in os.walk(target, followlinks=False):
            root_path = Path(root)
            dirs[:] = sorted(
                name for name in dirs
                if not (root_path / name).is_symlink()
            )
            for name in sorted(names):
                item = root_path / name
                if item.is_symlink() or not item.is_file():
                    continue
                files.append(self.track_file(item))
        return files

    def move_path(self, source: Path, destination: Path, *, recursive: bool = False) -> None:
        """Move provenance rows in place so canonical object IDs and attachments survive."""
        source_path = self._safe_path(source)
        destination_path = self._safe_path(destination)
        if not self.enabled:
            return
        if recursive:
            old_prefix, new_prefix = str(source_path) + "/", str(destination_path) + "/"
            self.db.execute(
                """
                UPDATE workstream_files
                SET path = %s || substr(path, length(%s) + 1),
                    source_job_id = %s
                WHERE left(path, length(%s)) = %s
                """,
                (new_prefix, old_prefix, self.job_id, old_prefix, old_prefix),
            )
        else:
            self.db.execute(
                """
                UPDATE workstream_files
                SET path = %s, source_job_id = %s
                WHERE path = %s
                """,
                (str(destination_path), self.job_id, str(source_path)),
            )

    def snapshot(self) -> dict[Path, tuple[str, int, int]]:
        """Hash regular workspace files while ignoring symlinks and protected paths."""
        snapshot: dict[Path, tuple[str, int, int]] = {}
        for root, dirs, names in os.walk(self.shared_root, followlinks=False):
            root_path = Path(root)
            dirs[:] = sorted(
                name for name in dirs
                if not (root_path / name).is_symlink()
                and not (root_path / name).relative_to(self.shared_root).parts[:2] == (".assistant", "docs")
            )
            for name in sorted(names):
                path = root_path / name
                if path.is_symlink() or not path.is_file():
                    continue
                try:
                    safe_path = self._safe_path(path)
                except ValueError:
                    continue
                file_stat = safe_path.stat()
                snapshot[safe_path] = (self._digest(safe_path), file_stat.st_dev, file_stat.st_ino)
        return snapshot

    def reconcile(
        self,
        before: dict[Path, tuple[str, int, int]],
        after: dict[Path, tuple[str, int, int]],
    ) -> None:
        """Record new/changed files and retain object identity for unambiguous moves."""
        removed = set(before) - set(after)
        added = set(after) - set(before)
        old_by_digest: dict[str, list[Path]] = {}
        new_by_digest: dict[str, list[Path]] = {}
        old_by_identity: dict[tuple[int, int], list[Path]] = {}
        new_by_identity: dict[tuple[int, int], list[Path]] = {}
        for path in removed:
            digest, device, inode = before[path]
            old_by_digest.setdefault(digest, []).append(path)
            old_by_identity.setdefault((device, inode), []).append(path)
        for path in added:
            digest, device, inode = after[path]
            new_by_digest.setdefault(digest, []).append(path)
            new_by_identity.setdefault((device, inode), []).append(path)

        moved_old: set[Path] = set()
        moved_new: set[Path] = set()
        for identity, old_paths in old_by_identity.items():
            new_paths = new_by_identity.get(identity, [])
            if len(old_paths) == len(new_paths) == 1:
                old_path, new_path = old_paths[0], new_paths[0]
                self.move_path(old_path, new_path)
                moved_old.add(old_path)
                moved_new.add(new_path)
        for digest, old_paths in old_by_digest.items():
            new_paths = new_by_digest.get(digest, [])
            old_paths = [path for path in old_paths if path not in moved_old]
            new_paths = [path for path in new_paths if path not in moved_new]
            if len(old_paths) == len(new_paths) == 1:
                old_path, new_path = old_paths[0], new_paths[0]
                self.move_path(old_path, new_path)
                moved_old.add(old_path)
                moved_new.add(new_path)

        for path, state in after.items():
            if path not in before or before[path][0] != state[0]:
                self.track_file(path)

    @staticmethod
    def _digest(path: Path) -> str:
        digest = hashlib.sha256()
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
        return digest.hexdigest()
